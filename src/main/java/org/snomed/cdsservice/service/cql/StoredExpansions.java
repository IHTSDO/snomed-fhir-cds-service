package org.snomed.cdsservice.service.cql;

import ca.uhn.fhir.context.FhirContext;
import org.hl7.fhir.r4.model.Coding;
import org.hl7.fhir.r4.model.Enumerations;
import org.hl7.fhir.r4.model.UriType;
import org.hl7.fhir.r4.model.ValueSet;
import org.snomed.cdsservice.service.ServiceException;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.Date;
import java.util.HexFormat;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

/**
 * ECL value set expansions kept on disk next to a content set ({@code <content set>/expansions/}), as FHIR ValueSets
 * with a populated {@code expansion}. Loading from here pins each value set to the SNOMED CT release it was expanded
 * and reviewed with, survives restarts, and needs no terminology server.
 * <p>
 * Each stored ValueSet records the ECL it was expanded from (in {@code compose}) and the SNOMED CT version (as the
 * expansion's {@code version} parameter). Codes are sorted so that a refresh shows up as a readable diff.
 */
public class StoredExpansions {

	public static final String DIRECTORY = "expansions";

	private static final String SNOMED = EclValueSetPreloader.SNOMED;
	private static final String VERSION_PREFIX = SNOMED + "|";

	/** An expansion read from disk. */
	public record Expansion(List<Coding> codings, String codeSystemVersion) {
	}

	private final FhirContext fhirContext;
	private final Path directory;
	private final List<ValueSet> valueSets = new ArrayList<>();

	private StoredExpansions(FhirContext fhirContext, Path directory) {
		this.fhirContext = fhirContext;
		this.directory = directory;
	}

	public static StoredExpansions load(FhirContext fhirContext, Path contentDirectory) throws IOException {
		StoredExpansions stored = new StoredExpansions(fhirContext, contentDirectory.resolve(DIRECTORY));
		if (Files.isDirectory(stored.directory)) {
			try (Stream<Path> files = Files.list(stored.directory)) {
				for (Path file : files.filter(f -> f.getFileName().toString().endsWith(".json")).sorted().toList()) {
					stored.valueSets.add(fhirContext.newJsonParser().parseResource(ValueSet.class, Files.readString(file)));
				}
			}
		}
		return stored;
	}

	/**
	 * @param key the URL the engine looks the value set up by: an implicit ECL URL, a canonical, or {@code canonical|version}
	 * @param ecl the ECL the content currently declares for it
	 * @throws ServiceException when the stored expansion was made from a different ECL, i.e. the content changed
	 *                          without refreshing its expansions
	 */
	public Optional<Expansion> find(String key, String ecl) throws ServiceException {
		Key parsed = Key.parse(key);
		for (ValueSet valueSet : valueSets) {
			if (!parsed.url().equals(valueSet.getUrl()) || (parsed.version() != null && !parsed.version().equals(valueSet.getVersion()))) {
				continue;
			}
			String storedEcl = storedEcl(valueSet);
			if (!ecl.equals(storedEcl)) {
				throw new ServiceException(("The stored expansion of '%s' was made from a different ECL ('%s'); the content now declares '%s'. "
						+ "Refresh the stored expansions (terminology.expansions.refresh=true) and review the result.").formatted(key, storedEcl, ecl));
			}
			List<Coding> codings = valueSet.getExpansion().getContains().stream()
					.map(contains -> new Coding(contains.getSystem(), contains.getCode(), contains.getDisplay()))
					.toList();
			return Optional.of(new Expansion(codings, storedVersion(valueSet)));
		}
		return Optional.empty();
	}

	/** Writes (or replaces) the stored expansion for {@code key}. */
	public void save(String key, String ecl, Collection<Coding> codings, String codeSystemVersion) throws IOException {
		Key parsed = Key.parse(key);
		ValueSet valueSet = new ValueSet();
		valueSet.setId(fileId(parsed.url()));
		valueSet.setUrl(parsed.url());
		if (parsed.version() != null) {
			valueSet.setVersion(parsed.version());
		}
		valueSet.setStatus(Enumerations.PublicationStatus.ACTIVE);
		valueSet.setDescription("Stored expansion of an ECL value set. Generated by the CDS service; review changes before committing.");
		ValueSet.ConceptSetComponent include = valueSet.getCompose().addInclude().setSystem(SNOMED);
		if (codeSystemVersion != null) {
			include.setVersion(codeSystemVersion);
		}
		include.addFilter().setProperty("constraint").setOp(ValueSet.FilterOperator.EQUAL).setValue(ecl);

		ValueSet.ValueSetExpansionComponent expansion = valueSet.getExpansion();
		expansion.setTimestamp(new Date());
		expansion.setTotal(codings.size());
		if (codeSystemVersion != null) {
			expansion.addParameter().setName("version").setValue(new UriType(VERSION_PREFIX + codeSystemVersion));
		}
		codings.stream()
				.sorted(Comparator.comparing(Coding::getCode))
				.forEach(coding -> expansion.addContains().setSystem(coding.getSystem()).setCode(coding.getCode()).setDisplay(coding.getDisplay()));

		Files.createDirectories(directory);
		Files.writeString(directory.resolve(valueSet.getIdPart() + ".json"),
				fhirContext.newJsonParser().setPrettyPrint(true).encodeResourceToString(valueSet) + "\n");
		valueSets.removeIf(existing -> existing.getUrl().equals(valueSet.getUrl()) && Objects.equals(existing.getVersion(), valueSet.getVersion()));
		valueSets.add(valueSet);
	}

	private static String storedEcl(ValueSet valueSet) {
		return valueSet.getCompose().getInclude().stream()
				.flatMap(include -> include.getFilter().stream())
				.filter(filter -> "constraint".equals(filter.getProperty()))
				.map(ValueSet.ConceptSetFilterComponent::getValue)
				.findFirst().orElse(null);
	}

	private static String storedVersion(ValueSet valueSet) {
		return valueSet.getExpansion().getParameter().stream()
				.filter(parameter -> "version".equals(parameter.getName()) && parameter.getValue() != null)
				.map(parameter -> parameter.getValue().primitiveValue())
				.filter(value -> value.startsWith(VERSION_PREFIX))
				.map(value -> value.substring(VERSION_PREFIX.length()))
				.findFirst().orElse(null);
	}

	/** Canonical ValueSets are named after their id; implicit ECL URLs after a hash of the URL. */
	static String fileId(String url) {
		if (url.startsWith(EclValueSetPreloader.IMPLICIT_ECL_PREFIX)) {
			try {
				byte[] digest = MessageDigest.getInstance("SHA-256").digest(url.getBytes(StandardCharsets.UTF_8));
				return "ecl-" + HexFormat.of().formatHex(digest, 0, 6);
			} catch (NoSuchAlgorithmException e) {
				throw new IllegalStateException(e);
			}
		}
		String id = url.substring(url.lastIndexOf('/') + 1).replaceAll("[^A-Za-z0-9.\\-]", "-");
		return "ValueSet-" + id;
	}

	/** Splits {@code canonical|version}; implicit ECL URLs may contain '|' inside the ECL and carry no version. */
	private record Key(String url, String version) {
		static Key parse(String key) {
			int bar = key.lastIndexOf('|');
			if (key.startsWith(EclValueSetPreloader.IMPLICIT_ECL_PREFIX) || bar < 0) {
				return new Key(key, null);
			}
			return new Key(key.substring(0, bar), key.substring(bar + 1));
		}
	}
}
